"""Streamlit UI for news sentiment prediction and model evaluation."""
from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

import joblib
import streamlit as st

LOGGER = logging.getLogger(__name__)
PROJECT_ROOT = Path(__file__).resolve().parent
MODEL_PATH = PROJECT_ROOT / "models" / "sentiment_pipeline.joblib"
METRICS_PATH = PROJECT_ROOT / "reports" / "metrics.json"

st.set_page_config(
    page_title="News Sentiment Classifier",
    page_icon="📰",
    layout="centered",
)


@st.cache_resource
def load_model() -> Any:
    """Load the trained text-classification pipeline."""
    if not MODEL_PATH.is_file():
        raise FileNotFoundError(
            "Trained model not found. Run "
            "`python -m src.train --data data/news_sentiment.csv` first."
        )
    return joblib.load(MODEL_PATH)


def load_metrics() -> dict[str, Any] | None:
    """Load model metrics generated by the training script."""
    if not METRICS_PATH.is_file():
        return None
    try:
        return json.loads(METRICS_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        LOGGER.exception("Could not read evaluation metrics.")
        st.warning(f"Could not read saved metrics: {exc}")
        return None


st.title("📰 News Sentiment Classifier")
st.caption("Classify a headline as positive, negative, or neutral.")

headline = st.text_area(
    "Enter a news headline",
    placeholder="Example: Stock markets rise after positive economic data",
    height=120,
)

if st.button("Analyze sentiment", type="primary"):
    if not headline.strip():
        st.warning("Please enter a news headline.")
    else:
        try:
            model = load_model()
            prediction = str(model.predict([headline.strip()])[0]).lower()
            labels = {
                "positive": "🟢 Positive",
                "negative": "🔴 Negative",
                "neutral": "🟡 Neutral",
            }
            st.subheader(f"Predicted sentiment: {labels.get(prediction, prediction.title())}")
            if hasattr(model, "predict_proba"):
                probabilities = model.predict_proba([headline.strip()])[0]
                class_names = model.classes_
                confidence = max(probabilities)
                st.metric("Model confidence", f"{confidence:.1%}")
                st.caption(
                    "Confidence is the model's estimated class probability, "
                    "not a guarantee that the prediction is correct."
                )
                st.bar_chart(
                    {str(name): float(prob) for name, prob in zip(class_names, probabilities)}
                )
        except FileNotFoundError as exc:
            st.error(str(exc))
        except (ValueError, OSError, RuntimeError) as exc:
            LOGGER.exception("Sentiment prediction failed.")
            st.error(f"Prediction failed: {exc}")

st.divider()
st.header("Model evaluation")
st.caption("Scores below are calculated from the held-out test set during training.")

metrics = load_metrics()
if metrics is None:
    st.info(
        "No evaluation report yet. Add the labelled CSV dataset and run the training "
        "command shown above to generate accuracy, precision, recall, F1-score, "
        "and the confusion matrix."
    )
else:
    first_row = st.columns(3)
    first_row[0].metric("Accuracy", f"{metrics['accuracy']:.2%}")
    first_row[1].metric("Macro F1-score", f"{metrics['f1_macro']:.2%}")
    first_row[2].metric("Weighted F1-score", f"{metrics['f1_weighted']:.2%}")

    second_row = st.columns(3)
    second_row[0].metric("Macro precision", f"{metrics['precision_macro']:.2%}")
    second_row[1].metric("Macro recall", f"{metrics['recall_macro']:.2%}")
    second_row[2].metric("Test samples", str(metrics["test_samples"]))

    report = metrics.get("classification_report", {})
    display_rows = []
    for label in metrics.get("classes", []):
        if label in report:
            entry = report[label]
            display_rows.append(
                {
                    "Class": label,
                    "Precision": entry.get("precision", 0.0),
                    "Recall": entry.get("recall", 0.0),
                    "F1-score": entry.get("f1-score", 0.0),
                    "Support": int(entry.get("support", 0)),
                }
            )
    if display_rows:
        st.subheader("Per-class metrics")
        st.dataframe(display_rows, use_container_width=True, hide_index=True)

    matrix = metrics.get("confusion_matrix")
    labels = metrics.get("classes")
    if matrix and labels:
        st.subheader("Confusion matrix")
        st.caption("Rows are actual labels; columns are predicted labels.")
        st.dataframe(
            {
                "Actual / Predicted": labels,
                **{
                    f"Predicted: {label}": [row[index] for row in matrix]
                    for index, label in enumerate(labels)
                },
            },
            use_container_width=True,
            hide_index=True,
        )
        matrix_image = PROJECT_ROOT / "reports" / "confusion_matrix.png"
        if matrix_image.is_file():
            st.image(str(matrix_image), caption="Confusion matrix heatmap", use_container_width=True)

    with st.expander("View full classification report (JSON)"):
        st.json(report)
